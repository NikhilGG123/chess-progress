#!/usr/bin/env bash
# Rebuilds supabase/setup_all.sql -- the single file that can be pasted into
# the Supabase SQL editor to take an empty project to a working demo.
#
# Run from the repo root:  bash supabase/build_setup_all.sh
set -euo pipefail

cd "$(dirname "$0")/.."

# Globbed, not listed. A hand-maintained list silently goes stale the moment
# somebody adds a migration and forgets this file -- which happened, and would
# have stood up a real deployment missing two migrations.
FILES=(
  supabase/migrations/*.sql
  supabase/seed/000_coaches.sql
)

{
  cat <<'HEADER'
-- =========================================================================
-- ONE-PASTE SETUP for the Supabase SQL editor.
--
-- Generated by joining every file in supabase/migrations/ in order, then the
-- coach rows.
--
-- PREFER `node scripts/apply-sql.mjs supabase/migrations/*.sql`, which runs
-- each file in its own transaction. The SQL editor wraps a whole paste in one,
-- and 0008 adds a value to an enum -- Postgres forbids *using* a new enum
-- value in the transaction that added it. Nothing here does, so this should
-- work; but if it stops on 0008, apply the migrations one at a time instead.
--
-- Do not edit this file. Edit the sources and regenerate:
--   bash supabase/build_setup_all.sh
--
-- Running it twice will fail on the first duplicate row -- that is deliberate,
-- it means the database already has this data.
-- =========================================================================

HEADER

  for f in "${FILES[@]}"; do
    printf '\n-- ===== %s =====\n\n' "$f"
    cat "$f"
  done
} > supabase/setup_all.sql

echo "Wrote supabase/setup_all.sql ($(wc -l < supabase/setup_all.sql) lines)"
